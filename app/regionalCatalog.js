function singaporeEnglish(text) {
  return text
    .replaceAll('factorization', 'factorisation')
    .replaceAll('Factorization', 'Factorisation')
    .replaceAll('GCF', 'HCF')
    .replaceAll('greatest common divisor', 'highest common factor')
    .replaceAll('Greatest common divisor', 'Highest common factor');
}

export function localizeRegionalUnit(unitId, language, englishText, field = 'label') {
  if (language === 'en-SG') return singaporeEnglish(englishText);
  const labels = language === 'zh-HK' ? zhHK : language === 'zh-TW' ? zhTW : null;
  if (!labels) return englishText;
  const label = labels[unitId];
  if (!label) return englishText;
  if (field === 'label') return label;
  return language === 'zh-HK' ? `練習「${label}」的核心題型。` : `練習「${label}」的核心題型。`;
}

export function localizeRegionalGrade(gradeId, language, englishText) {
  if (language === 'en-SG') return `Primary ${gradeId}`;
  if (language === 'zh-HK') return `小學${['一', '二', '三', '四', '五', '六'][Number(gradeId) - 1]}年級`;
  if (language === 'zh-TW') return `國小${['一', '二', '三', '四', '五', '六'][Number(gradeId) - 1]}年級`;
  return englishText;
}
