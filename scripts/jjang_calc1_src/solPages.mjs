// 한 쪽에 여러 문제가 모여 있으므로 화면에서는 이 쪽과 다음 쪽을 함께 열람할 수 있게 한다.
// [마지막 문항번호, 쪽] 오름차순.
export const SOL_PAGES = {
  1: [[25, 1], [31, 2]],
  2: [[20, 4]],
  3: [[13, 5], [25, 6], [31, 7]],
  4: [[10, 8], [14, 9]],
  5: [[6, 10], [10, 11], [14, 12], [16, 13]],
  6: [[9, 14], [29, 15]],
  7: [[12, 16], [24, 17], [30, 18]],
  8: [[12, 20], [22, 21], [28, 22]],
  9: [[24, 24], [30, 25]],
  10: [[12, 27], [24, 28], [30, 29]],
  11: [[25, 31], [31, 33]],
  12: [[12, 35], [18, 36]],
  13: [[17, 38]],
  14: [[24, 40], [30, 42]],
  15: [[24, 44], [30, 45]],
  16: [[12, 47], [22, 48], [28, 49]],
  17: [[11, 51], [16, 52], [20, 54]],
};

export function solPageFor(typeNo, number) {
  const table = SOL_PAGES[typeNo];
  if (!table) return null;
  for (const [last, page] of table) if (number <= last) return page;
  return table[table.length - 1][1];
}
